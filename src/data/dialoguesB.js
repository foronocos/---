/**
 * Диалоги Акта II: подъезд, подвал, чердак, крыша, затмение и небо.
 * Тот же формат узлов, что и в первом акте: текст, следующий узел, выборы, эффекты.
 */

function seq(lines, options = {}) {
  const nodes = {};
  lines.forEach((entry, index) => {
    const [speaker, text, extra] = Array.isArray(entry) ? entry : ['', entry];
    nodes[`n${index}`] = {
      speaker,
      text,
      tone: options.tone || (speaker ? 'speech' : 'narration'),
      ...(extra || {}),
      next: index < lines.length - 1 ? `n${index + 1}` : undefined,
      end: index === lines.length - 1,
    };
  });
  if (options.enterEffects && lines.length) {
    nodes.n0.effects = { ...(nodes.n0.effects || {}), ...options.enterEffects };
  }
  if (options.endEffects && lines.length) {
    const last = nodes[`n${lines.length - 1}`];
    last.effects = { ...(last.effects || {}), ...options.endEffects };
  }
  return { start: 'n0', nodes };
}

function node(text, options = {}) {
  return { speaker: '', tone: 'narration', text, ...options };
}

function say(speaker, text, options = {}) {
  return { speaker, tone: 'speech', text, ...options };
}

function noteDialogue(noteId) {
  const note = NOTES_ACT2[noteId];
  if (!note) return seq([['', 'Здесь ничего не написано. Только пыль.']]);
  return seq([[note.title, note.text, { tone: 'note', noteTitle: note.title }]], {
    tone: 'note',
    enterEffects: { note: noteId, toast: `Записка в журнале: «${note.title}»` },
  });
}

