import { bossResolved, allyCount } from '../game/state.js';
import { NOTES } from './notes.js';

export function mainObjective(state) {
  const player = state.player;
  if (state.chapter === 1) {
    if (!bossResolved(player, 'cat')) {
      return {
        title: 'Найти пропавшее Золотое Перо',
        text: 'Балконная дверь пуста, солнце не встало. На диване спит кот — он явно знает больше, чем говорит.',
        hint: 'Подойди к дивану в гостиной. Заодно осмотри комнату: записки и тайники.',
      };
    }
    return {
      title: 'Выйти из гостиной',
      text: 'Кот больше не преграждает путь. Дверь в коридор открыта, а где-то там — кладовка и балкон.',
      hint: 'Иди вправо, в коридор. Дверь в кладовку теперь не заперта.',
    };
  }
  if (state.chapter === 2) {
    if (!bossResolved(player, 'vacuum')) {
      return {
        title: 'Обыскать кладовку',
        text: 'В глубине кладовки гудит что-то древнее. Оно глотает вещи уже много лет — и, кажется, перо тоже.',
        hint: 'Исследуй полки, вентиляцию и глубокий проход. Тайники дают Семена Силы.',
      };
    }
    return {
      title: 'Вернуться в коридор',
      text: 'В мешке нашёлся запасной ключ. Кухня ждёт, а за ней — балкон.',
      hint: 'Выйди из кладовки и иди в коридор: дверь на кухню открыта.',
    };
  }
  if (state.chapter === 3) {
    if (!bossResolved(player, 'pasta')) {
      return {
        title: 'Пройти на балкон',
        text: 'Балконная дверь близко, но у плиты стоит тот, кто варил эту квартиру. Он не пропустит без проверки.',
        hint: 'Поговори с Хозяином Макарон. Перед боем проверь инвентарь и улучшения.',
      };
    }
    if (!player.keyItems.key) {
      return {
        title: 'Найти ключ от балкона',
        text: 'Хозяин Макарон больше не мешает, но дверь заперта. Запасной ключ где-то в квартире.',
        hint: 'Вернись в кладовку: ключ был в мешке пылесоса.',
      };
    }
    if (!player.keyItems.feather) {
      return {
        title: 'Найти Золотое Перо',
        text: 'Ключ есть, а без пера утро всё равно не наступит. Перо должно быть в мешке пылесоса.',
        hint: 'Проверь глубину кладовки.',
      };
    }
    return {
      title: 'Открыть балконную дверь',
      text: 'Ключ в клюве, перо под крылом. Пора выходить.',
      hint: 'Подойди к двери в правом конце кухни.',
    };
  }
  if (state.chapter === 5) {
    if (!bossResolved(player, 'keys')) {
      return {
        title: 'Пройти подъезд',
        text: 'Дом кончился на двери квартиры — и продолжился лестницей. На площадке висит связка ключей, и она не рада гостям.',
        hint: 'Поговори с Ключницей. Заодно осмотри почтовые ящики и объявления.',
      };
    }
    return {
      title: 'Спуститься в подвал',
      text: 'Ключница открыла двери. Внизу греет дом, наверху хранит память — а перо унесло ещё выше.',
      hint: 'Дверь в подвал — на площадке, слева.',
    };
  }
  if (state.chapter === 6) {
    if (!bossResolved(player, 'boiler')) {
      return {
        title: 'Найти тепло дома',
        text: 'В котельной живёт тот, кто греет весь дом и ворчит на весь дом. Без его тепла осколок пера не поднимется выше.',
        hint: 'Поговори с Котлом-Ворчуном. Он любит, когда его благодарят.',
      };
    }
    return {
      title: 'Подняться на чердак',
      text: 'Котёл отдал тепло. Теперь нужна память: то, что хранится под самой крышей.',
      hint: 'Вернись на площадку и поднимись на чердак.',
    };
  }
  if (state.chapter === 7) {
    if (!bossResolved(player, 'moth')) {
      return {
        title: 'Договориться с памятью',
        text: 'Моль-Хранительница ест то, что забыли. В её крыльях — узор из чужих свитеров и, кажется, второй осколок пера.',
        hint: 'Ищи сундучный угол в конце чердака.',
      };
    }
    return {
      title: 'Выйти на крышу',
      text: 'Люк открыт: память отпустила. Впереди ветер и город, а над ними — та, кто держит ночь.',
      hint: 'Люк на крышу — посередине чердака.',
    };
  }
  if (state.chapter === 8) {
    if (!bossResolved(player, 'raven')) {
      return {
        title: 'Пройти антенное поле',
        text: 'На крыше хозяйничает Ворон: собирает всё блестящее и не любит делиться. За антеннами начинается затмение.',
        hint: 'Антенное поле — в правом конце крыши.',
      };
    }
    return {
      title: 'Войти в затмение',
      text: 'Ворон пропустил. Дальше дорога обрывается в темноту, и в этой темноте тебя уже ждут.',
      hint: 'Дверь в затмение — в конце антенного поля.',
    };
  }
  if (state.chapter === 9) {
    if (!bossResolved(player, 'shadow')) {
      return {
        title: 'Поговорить со своей тенью',
        text: 'Зеркальная площадка показывает всё, что ты не решился сказать. Тень ждёт и не нападает первой.',
        hint: 'Подойди к зеркалу в центре площадки.',
      };
    }
    return {
      title: 'Подняться в гнездо',
      text: 'Тень отпустила. Выше только гнездо из проводов и облаков — и та, кто держит затмение.',
      hint: 'Дверь в гнездо — справа на площадке.',
    };
  }
  if (state.chapter === 10) {
    if (!bossResolved(player, 'shunya')) {
      return {
        title: 'Встретить Шуню',
        text: 'Она забрала перо у того, кто боялся выйти. Ты вышел. Осталось объяснить ей, что это значит.',
        hint: 'Шуня ждёт в гнезде. Доброта и союзники откроют мирный путь.',
      };
    }
    return {
      title: 'Решить судьбу рассвета',
      text: 'Перо вернулось. За гнездом — небо, внизу — дом, за спиной — все, кто шёл рядом.',
      hint: 'Иди к краю гнезда: там решается, каким будет утро.',
    };
  }
  return {
    title: 'Встретить утро',
    text: 'Балкон открыт. Осталось решить, что делать с пером и с собой.',
    hint: 'Финальный выбор определит концовку — но не только он.',
  };
}

export function sideQuests(state) {
  const player = state.player;
  const noteCount = player.notesRead.length;
  const visited = state.visited.length;
  return [
    {
      id: 'seeds',
      title: 'Семена Силы',
      text: `Собрано: ${player.seeds}. Трать на улучшения и предметы у торговцев.`,
      done: player.seeds >= 6,
    },
    {
      id: 'notes',
      title: 'Записки квартиры',
      text: `Прочитано ${noteCount} из ${Object.keys(NOTES).length}.`,
      done: noteCount >= Object.keys(NOTES).length,
    },
    {
      id: 'bestiary',
      title: 'Бестиарий',
      text: `Записано ${player.bestiarySeen.length} существ.`,
      done: player.bestiarySeen.length >= 13,
    },
    {
      id: 'allies',
      title: 'Не в одиночку',
      text: `Союзников: ${allyCount(player)}.`,
      done: allyCount(player) >= 2,
    },
    {
      id: 'rooms',
      title: 'Квартира выросла',
      text: `Исследовано комнат: ${visited} из 20.`,
      done: visited >= 20,
    },
  ];
}

export function journalSummary(state) {
  const player = state.player;
  const outcomes = Object.values(player.bosses);
  return {
    kills: outcomes.filter((value) => value === 'kill').length,
    spares: outcomes.filter((value) => value === 'spare').length,
    kindness: player.kindness,
    greed: player.greed,
  };
}
